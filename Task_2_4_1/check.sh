#!/bin/bash

CONFIG=${1:-config.groovy}
REPORT=${2:-report.html}

echo "🚀 Запуск автоматической проверки ООП..."
echo "📄 Используем конфигурацию: $CONFIG"
echo "📊 Результат будет сохранен в: $REPORT"
echo "--------------------------------------------------------"

# Используем ключ -q, чтобы скрыть логи Gradle.
# HTML-отчет пишет само приложение в путь REPORT (3-й аргумент команды report).
./gradlew -q run --args="report $CONFIG $REPORT"

echo "--------------------------------------------------------"
echo "✅ Проверка завершена!"
echo "🌐 Итоговый отчет сгенерирован: $REPORT"
